#!/usr/bin/env node
// Scans src/modules/installed/ for module submodules and generates src/modules/devModules.ts,
// which registers each one it finds.
//
// This is the source-linked path: a module checked out here is compiled into the bundle and
// gets hot reload, which is how you develop one. The other path is production, where modules
// are federated remotes the backend serves and the loader pulls in at runtime.
//
// Both end at the same registerModule() call, and registration is keyed, so whichever arrives
// first wins - a module checked out here shadows the remote of the same name rather than
// fighting it. That also means the choice is made by what is on disk at build time: build with
// the submodules checked out to bundle them, without to load them as remotes.

const fs = require('fs');
const path = require('path');

const modulesDir = path.join(__dirname, '..', 'src', 'modules');
const installedDir = path.join(modulesDir, 'installed');
const outputFile = path.join(modulesDir, 'devModules.ts');

const moduleDirs = fs.existsSync(installedDir)
  ? fs.readdirSync(installedDir).filter((name) => {
      const fullPath = path.join(installedDir, name);
      return (
        fs.statSync(fullPath).isDirectory() &&
        fs.existsSync(path.join(fullPath, 'index.ts'))
      );
    })
  : [];

const capitalize = (s) => s.charAt(0).toUpperCase() + s.slice(1);

const header =
  '// AUTO-GENERATED by scripts/generate-registry.js — do not edit manually\n' +
  "import { registerModule } from './registry';\n";

const content = moduleDirs.length > 0
  ? header +
    moduleDirs
      .map((name) => `import ${capitalize(name)}Module from './installed/${name}';`)
      .join('\n') +
    '\n\n// Modules checked out as submodules, compiled into this build.\n' +
    'export default function registerSourceModules() {\n' +
    moduleDirs.map((name) => `  registerModule(${capitalize(name)}Module);`).join('\n') +
    '\n}\n'
  : header +
    '\n// No module submodules checked out - modules will be loaded as federated remotes.\n' +
    'export default function registerSourceModules() {}\n';

fs.writeFileSync(outputFile, content);

if (moduleDirs.length > 0) {
  console.log(`[generate-registry] Source modules: ${moduleDirs.join(', ')}`);
} else {
  console.log('[generate-registry] No module submodules found - remotes only.');
}
