#!/usr/bin/env node
// Scans src/modules/ for subdirectories containing an index.ts and generates
// src/modules/registry.ts. Run this before building so that only the module
// submodules the user has cloned are included in the bundle.

const fs = require('fs');
const path = require('path');

const modulesDir = path.join(__dirname, '..', 'src', 'modules');
const outputFile = path.join(modulesDir, 'registry.ts');

// A valid module submodule directory must contain an index.ts
const moduleDirs = fs.readdirSync(modulesDir).filter((name) => {
  const fullPath = path.join(modulesDir, name);
  return (
    fs.statSync(fullPath).isDirectory() &&
    fs.existsSync(path.join(fullPath, 'index.ts'))
  );
});

const capitalize = (s) => s.charAt(0).toUpperCase() + s.slice(1);

const importLines = moduleDirs
  .map((name) => `import ${capitalize(name)}Module from './${name}';`)
  .join('\n');

const moduleList = moduleDirs
  .map((name) => `  ${capitalize(name)}Module`)
  .join(',\n');

const content = moduleDirs.length > 0
  ? `// AUTO-GENERATED by scripts/generate-registry.js — do not edit manually\nimport type { ModuleDefinition } from './types';\n${importLines}\n\nexport const modules: ModuleDefinition[] = [\n${moduleList},\n];\n`
  : `// AUTO-GENERATED by scripts/generate-registry.js — do not edit manually\nimport type { ModuleDefinition } from './types';\n\nexport const modules: ModuleDefinition[] = [];\n`;

fs.writeFileSync(outputFile, content);

if (moduleDirs.length > 0) {
  console.log(`[generate-registry] Registered modules: ${moduleDirs.join(', ')}`);
} else {
  console.log('[generate-registry] No module submodules found. Registry is empty.');
}
